function normalize(name: string): string {
  return name
    .replace(/[-־_]/g, " ")
    .replace(/["'׳״]/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

const INDEX = new Map<string, { lat: number; lon: number; name: string }>();
for (const [names, lat, lon] of CITIES) {
  for (const n of names) INDEX.set(normalize(n), { lat, lon, name: names[0] });
}

export function findIsraeliCity(input: string) {
  return INDEX.get(normalize(input)) ?? null;
}
